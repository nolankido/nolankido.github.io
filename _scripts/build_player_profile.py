#!/usr/bin/env python3
"""Build the standalone poker player profile without changing the main site generator.

The main website build owns its manifest pages. This separately owned public
profile intentionally does not carry its Generated marker. It inherits the
current published Poker shell and is checked locally, never with GitHub Actions.
"""
from __future__ import annotations

import argparse
from html import escape
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "_source/poker/nolan-kido-profile.html"
HUB = ROOT / "poker/index.html"
OUTPUT = ROOT / "poker/nolan-kido/index.html"
ORIGIN = "https://nolankido.com"
URL = ORIGIN + "/poker/nolan-kido/"
TITLE = "Nolan Kido: Tournament Poker Player | Results & Vlog Plans"
DESCRIPTION = ("Nolan Kido's live tournament poker record, including independent WSOP "
               "and South Point results, plus his approach to reviewing poker hands.")
OLD_TITLE = "Learn Poker: Free Beginner Course & Resources | Nolan Kido"
OLD_DESCRIPTION = ("Start Poker Foundations, a free Texas Hold’em beginner course. "
                   "Practice decisions, prepare for live play and explore guides and outside resources.")
SOURCE_MARKER = "<!-- Generated by _scripts/build.py; edit _source files. -->"
MANUAL_MARKER = "<!-- Player profile: edit _source/poker/nolan-kido-profile.html; build with _scripts/build_player_profile.py. -->"
MAIN_START = '  <main id="main" class="ledger" tabindex="-1">'
MAIN_END = "  </main>"


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError("Profile shell requires exactly one anchor: " + old[:90])
    return text.replace(old, new, 1)


def render() -> str:
    hub = HUB.read_text(encoding="utf-8")
    body = SOURCE.read_text(encoding="utf-8")
    if SOURCE_MARKER not in hub or body.count('id="player-intro-title"') != 1:
        raise ValueError("Published Poker shell or profile body is missing")
    if "—" in body or '<script' in body.lower() or '<form' in body.lower():
        raise ValueError("Profile must remain static, free of forms and em dashes")
    if hub.count(MAIN_START) != 1 or hub.count(MAIN_END) != 1:
        raise ValueError("Published Poker shell has ambiguous main landmarks")
    prefix, remainder = hub.split(MAIN_START)
    old_main, suffix = remainder.split(MAIN_END)
    prefix = replace_once(prefix, SOURCE_MARKER, MANUAL_MARKER)
    for old, new in (
        (f"<title>{escape(OLD_TITLE)}</title>", f"<title>{escape(TITLE)}</title>"),
        (f'<meta name="description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta name="description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<meta property="og:title" content="{escape(OLD_TITLE, quote=True)}">',
         f'<meta property="og:title" content="{escape(TITLE, quote=True)}">'),
        (f'<meta property="og:description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta property="og:description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<meta property="og:url" content="{ORIGIN}/poker/">',
         f'<meta property="og:url" content="{URL}">'),
        (f'<meta name="twitter:title" content="{escape(OLD_TITLE, quote=True)}">',
         f'<meta name="twitter:title" content="{escape(TITLE, quote=True)}">'),
        (f'<meta name="twitter:description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta name="twitter:description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<link rel="canonical" href="{ORIGIN}/poker/">',
         f'<link rel="canonical" href="{URL}">'),
        ('<body class="site-page page-poker">',
         '<body class="site-page page-poker-player">'),
    ):
        prefix = replace_once(prefix, old, new)
    if prefix.count('href="/poker/" aria-current="page"') != 2:
        raise ValueError("Profile expects two Poker navigation current-state links")
    prefix = prefix.replace('href="/poker/" aria-current="page"',
                            'href="/poker/" aria-current="location"')
    pattern = r'<script type="application/ld\+json">(.*?)</script>'
    match = re.search(pattern, prefix, flags=re.S)
    if match is None or len(re.findall(pattern, prefix, flags=re.S)) != 1:
        raise ValueError("Profile needs exactly one JSON-LD record")
    schema = json.loads(match.group(1))
    schema.update({
        "@type": "WebPage",
        "@id": URL + "#webpage",
        "name": TITLE,
        "url": URL,
        "description": DESCRIPTION,
        "dateModified": "2026-11-01",
        "about": {"@type": "Person", "@id": ORIGIN + "/about/#nolan-kido",
                  "name": "Nolan Kido", "url": ORIGIN + "/about/"},
        "breadcrumb": {
            "@type": "BreadcrumbList", "@id": URL + "#breadcrumb",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": ORIGIN + "/"},
                {"@type": "ListItem", "position": 2, "name": "Poker", "item": ORIGIN + "/poker/"},
                {"@type": "ListItem", "position": 3, "name": "Nolan Kido at tournaments", "item": URL},
            ],
        },
    })
    prefix = prefix[:match.start(1)] + json.dumps(schema, ensure_ascii=False).replace("<", "\\u003c") + prefix[match.end(1):]
    player_main = (
        '\n<nav class="search-breadcrumb shell" aria-label="Breadcrumb">'
        '<ol><li><a href="/">Home</a></li><li><a href="/poker/">Poker</a></li>'
        '<li><span aria-current="page">Nolan Kido at tournaments</span></li></ol></nav>\n'
        '    <section class="page-hero shell"><p class="page-kicker">Poker / Player record</p>'
        '<h1 class="page-title">Nolan Kido: Tournament Poker Player</h1></section>\n'
        + body
    )
    rendered = prefix + MAIN_START + player_main + MAIN_END + suffix
    if rendered.count('<h1 ') != 1 or rendered.count('aria-label="Breadcrumb"') != 1:
        raise ValueError("Profile must have one H1 and one breadcrumb")
    if SOURCE_MARKER in rendered or "—" in rendered:
        raise ValueError("Player page cannot masquerade as a main-generator page")
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare published page without writing")
    args = parser.parse_args()
    try:
        html = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != html:
                print("Standalone player profile differs from source; rebuild locally", file=sys.stderr)
                return 1
            print("Standalone player profile: exact source match")
            return 0
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(html, encoding="utf-8", newline="")
        print("Built " + str(OUTPUT.relative_to(ROOT)))
        return 0
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print("Player profile build error: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
