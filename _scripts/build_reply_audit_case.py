#!/usr/bin/env python3
"""Build the reviewed independent AI-reply case without taking over main page routes.

No network calls, GitHub Actions, remote models, or machine-specific readouts.
The source guide is its own editorial record and uses the site's existing
technology article shell to preserve navigation, sharing, and stable identity.
"""
from __future__ import annotations

import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "_source/technology/review-reply-evidence-audit.html"
SHELL = ROOT / "technology/local-ai-test-record/index.html"
OUTPUT = ROOT / "technology/review-reply-evidence-audit/index.html"
URL = "https://nolankido.com/technology/review-reply-evidence-audit/"
TITLE = "Checking AI Replies Against the Source | Nolan Kido"
HEADLINE = "What a second check found in three AI-written replies."
DESCRIPTION = ("An independent audit of three recorded Gemma replies: factual omissions, "
               "unauthorized promises, synthetic controls, and human review limits.")
PUBLISHED = "2026-11-03"
MODIFIED = "2026-11-05"
PERSON = "https://nolankido.com/about/#nolan-kido"
OLD_TITLE = "Local AI Test Results: Timing, Errors & Limits | Nolan Kido"
OLD_DESCRIPTION = ("Read a documented Gemma test on an Ubuntu CPU runner: per-case timings, "
                   "retained failures, configuration, and the difference between model latency and task time.")
OLD_URL = "https://nolankido.com/technology/local-ai-test-record/"
MARKER = "<!-- Generated by _scripts/build.py; edit _source files. -->"
MANUAL = "<!-- Independent reply audit: edit _source/technology/review-reply-evidence-audit.html; build with _scripts/build_reply_audit_case.py. -->"
MAIN = '  <main id="main" class="ledger" tabindex="-1">'
END_MAIN = "  </main>"


def once(content: str, old: str, new: str) -> str:
    if content.count(old) != 1:
        raise ValueError("Expected exactly one local AI shell anchor: " + old[:90])
    return content.replace(old, new, 1)


def date_label(value: str) -> str:
    stamp = date.fromisoformat(value)
    return f'{stamp.strftime("%B")} {stamp.day}, {stamp.year}'


def render() -> str:
    shell = SHELL.read_text(encoding="utf-8")
    source = SOURCE.read_text(encoding="utf-8")
    if shell.count(MAIN) != 1 or shell.count(END_MAIN) != 1 or not source.startswith('<article'):
        raise ValueError("Local guide needs an original article and a stable public shell")
    if "—" in source or "<iframe" in source.lower() or "<script" in source.lower():
        raise ValueError("Guide must not embed scripts, remote players or em dashes")
    prefix, tail = shell.split(MAIN, 1)
    old_body, suffix = tail.split(END_MAIN, 1)
    prefix = once(prefix, MARKER, MANUAL)
    for old, new in (
        (f"<title>{escape(OLD_TITLE)}</title>", f"<title>{escape(TITLE)}</title>"),
        (f'<meta name="description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta name="description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<meta property="og:title" content="{escape(OLD_TITLE, quote=True)}">',
         f'<meta property="og:title" content="{escape(TITLE, quote=True)}">'),
        (f'<meta property="og:description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta property="og:description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<meta property="og:url" content="{OLD_URL}">',
         f'<meta property="og:url" content="{URL}">'),
        (f'<meta name="twitter:title" content="{escape(OLD_TITLE, quote=True)}">',
         f'<meta name="twitter:title" content="{escape(TITLE, quote=True)}">'),
        (f'<meta name="twitter:description" content="{escape(OLD_DESCRIPTION, quote=True)}">',
         f'<meta name="twitter:description" content="{escape(DESCRIPTION, quote=True)}">'),
        (f'<link rel="canonical" href="{OLD_URL}">',
         f'<link rel="canonical" href="{URL}">'),
        ('<body class="site-page page-local-ai-test-record">',
         '<body class="site-page page-review-reply-evidence-audit">'),
        ('<meta property="article:published_time" content="2026-10-27">',
         '<meta property="article:published_time" content="' + PUBLISHED + '">\n'
         '  <meta property="article:modified_time" content="' + MODIFIED + '">'),
        ('/assets/social/reader-local-ai-test-record.png',
         '/assets/social/practical-ai.png'),
        ('PRACTICAL AI / RECORDED CASE. What a local AI test actually measured. Nolan Kido. nolankido.com.',
         'Nolan Kido. Practical AI for real life. Useful tools, clear checks, and your judgment.'),
    ):
        if old.startswith("/assets/social/") or old.startswith("PRACTICAL AI /"):
            if prefix.count(old) != 2:
                raise ValueError("Expected matching Open Graph and Twitter image metadata")
            prefix = prefix.replace(old, new)
        else:
            prefix = once(prefix, old, new)
    pattern = r'<script type="application/ld\+json">(.*?)</script>'
    hit = re.search(pattern, prefix, re.S)
    if hit is None or len(re.findall(pattern, prefix, re.S)) != 1:
        raise ValueError("Local AI case needs one structured-data record")
    schema = json.loads(hit.group(1))
    if schema.get('@type') != 'Article' or schema.get('author', {}).get('@id') != PERSON:
        raise ValueError("Local AI case requires the site's existing author identity")
    schema.update({
        "name": TITLE, "headline": HEADLINE, "url": URL, "description": DESCRIPTION,
        "datePublished": PUBLISHED, "dateModified": MODIFIED, "@id": URL + "#article",
        "mainEntityOfPage": {
            "@type": "WebPage", "@id": URL + "#webpage", "url": URL,
            "breadcrumb": {
                "@type": "BreadcrumbList", "@id": URL + "#breadcrumb",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": "Home", "item": "https://nolankido.com/"},
                    {"@type": "ListItem", "position": 2, "name": "Technology", "item": "https://nolankido.com/technology/"},
                    {"@type": "ListItem", "position": 3, "name": HEADLINE, "item": URL},
                ],
            },
        },
    })
    prefix = (prefix[:hit.start(1)] + json.dumps(schema, ensure_ascii=False).replace("<", "\\u003c")
              + prefix[hit.end(1):])
    leading = (
        '\n<nav class="search-breadcrumb shell" aria-label="Breadcrumb">'
        '<ol><li><a href="/">Home</a></li><li><a href="/technology/">Technology</a></li>'
        '<li><span aria-current="page">' + escape(HEADLINE) + '</span></li></ol></nav>\n'
        '    <section class="page-hero shell">'
        '<p class="page-kicker">Technology / Practical AI / Independent checking</p>'
        '<h1 class="page-title">' + escape(HEADLINE) + '</h1>'
        '<p class="note-meta">Published <time datetime="' + PUBLISHED +
        '">' + date_label(PUBLISHED) + '</time> · Updated <time datetime="' + MODIFIED +
        '">' + date_label(MODIFIED) + '</time> · Recorded workflow · Separate quality screen</p>'
        '<p class="search-author">By <a href="/about/" rel="author">Nolan Kido</a> · '
        '<a href="/start-here/#reading-this-site">About this writing</a></p>'
        '</section>\n'
    )
    rendered = prefix + MAIN + leading + source + END_MAIN + suffix
    if rendered.count('<h1 ') != 1 or rendered.count('aria-label="Breadcrumb"') != 1:
        raise ValueError("Local AI guide must have one H1 and one breadcrumb")
    if MARKER in rendered or "—" in rendered:
        raise ValueError("Local AI guide must remain separately source owned")
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Read-only exact source equality check")
    args = parser.parse_args()
    try:
        html = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != html:
                print("Independent reply audit differs from approved source", file=sys.stderr)
                return 1
            print("Independent reply audit: exact source match")
            return 0
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(html, encoding="utf-8", newline="")
        print("Built " + str(OUTPUT.relative_to(ROOT)))
        return 0
    except (ValueError, OSError, KeyError, TypeError) as exc:
        print("Independent reply audit build error: " + str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
