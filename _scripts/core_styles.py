"""One cacheable core stylesheet, preserving every declaration and its order.

The original three source files remain the editable sources. No minification,
font changes, asynchronous styling, or critical-CSS heuristics are involved.
"""
from hashlib import sha256
from pathlib import Path
import re
from urllib.parse import urlsplit

SOURCES = ('styles.css', 'assets/site.css', 'assets/hubs.css')
OUTPUT = Path('assets/site-core.css')
LINK = re.compile(r'<link\b[^>]*>', re.I)
HREF = re.compile(r'\bhref="([^"<>]+)"')
REL = re.compile(r'\brel="stylesheet"')


def bundle(root: Path) -> str:
    parts = []
    for name in SOURCES:
        source = (root / name).read_text(encoding='utf-8')
        # Moving relative URLs changes their base; top-level imports/namespace
        # declarations need a separate design. Fail rather than change meaning.
        if re.search(r'@(?:import|charset|namespace)\b|url\s*\(', source, re.I):
            raise ValueError('Core CSS requires explicit URL/at-rule review: ' + name)
        parts.append('/* Source: ' + name + ' */\n' + source + '\n')
    return '/* Generated by _scripts/core_styles.py; edit the source files. */\n' + '\n'.join(parts)


def href(content: str) -> str:
    return '/' + OUTPUT.as_posix() + '?v=' + sha256(content.encode('utf-8')).hexdigest()[:12]


def collapse(document: str, destination: str) -> str:
    selected = []
    for match in LINK.finditer(document):
        link = match.group()
        target = HREF.search(link)
        if REL.search(link) and target:
            parsed = urlsplit(target.group(1))
            if not parsed.scheme and not parsed.netloc and parsed.path.lstrip('/') in SOURCES:
                if not parsed.path.startswith('/'):
                    raise ValueError('Core stylesheet paths must be absolute')
                # The original links are unconditional; do not silently collapse
                # a future media, integrity, or alternate loading contract.
                if not re.fullmatch(r'<link rel="stylesheet" href="[^"<>]+">', link):
                    raise ValueError('Unexpected core stylesheet attributes')
                selected.append((match, parsed.path.lstrip('/')))
    if tuple(name for _, name in selected) != SOURCES:
        raise ValueError('Expected one ordered set of three core stylesheet links')
    start, end = selected[0][0].start(), selected[-1][0].end()
    between = document[start:end]
    for match, _ in selected:
        between = between.replace(match.group(), '', 1)
    if between.strip():
        raise ValueError('Do not move core CSS across intervening page-head content')
    return document[:start] + '<link rel="stylesheet" href="' + destination + '">' + document[end:]


def apply(outputs: dict[Path, str], root: Path) -> dict[Path, str]:
    content = bundle(root)
    destination = href(content)
    for path, document in list(outputs.items()):
        if path.suffix == '.html':
            outputs[path] = collapse(document, destination)
    outputs[OUTPUT] = content
    return outputs
